int32 FInkpotNativeBindingGenerationReport::NumWritten() const
{
	int32 count = 0;
	for (const FInkpotNativeBindingGeneratedLoader& loader : Loaders)
		if (loader.bWritten) ++count;
	return count;
}

FString FInkpotNativeBindingGenerationReport::ToString() const
{
	FString result = FString::Printf(TEXT("Native binding modules in %s: %d module(s), %d loader(s) ( %d written ), %d error(s), %d warning(s)%s."),
		*Directory, Modules.Num(), Loaders.Num(), NumWritten(), Errors.Num(), Warnings.Num(), bManifestUsed ? TEXT(", checked against the Prosetta manifest") : TEXT(", no manifest"));
	for (const FInkpotNativeBindingSourceModule& module : Modules)
	{
		result += FString::Printf(TEXT("\n  %s [%s] %s: %d function(s), %d error(s), %d warning(s)"), module.ModuleName.IsEmpty() ? TEXT("<unknown>") : *module.ModuleName,
			module.Provenance.bPresent ? TEXT("prosetta") : TEXT("local"), *FPaths::GetCleanFilename(module.Filename), module.Functions.Num(), module.ErrorCount(), module.WarningCount());
		for (const FInkpotNativeBindingSourceFunction& function : module.Functions)
			result += FString::Printf(TEXT("\n      %s%s%s"), *function.Signature(), function.bLookaheadSafe ? TEXT("  // @lookaheadSafe") : TEXT(""), function.bStub ? TEXT("  // stub") : TEXT(""));
		for (const FInkpotNativeBindingSourceDiagnostic& diagnostic : module.Diagnostics)
			result += TEXT("\n      ") + diagnostic.ToString();
	}
	for (const FInkpotNativeBindingGeneratedLoader& loader : Loaders)
		result += FString::Printf(TEXT("\n  loader %s: %s"), *FPaths::GetCleanFilename(loader.LoaderFile), loader.bWritten ? TEXT("written") : loader.bChanged ? TEXT("out of date") : TEXT("up to date"));
	for (const FString& error : Errors)
		result += TEXT("\n  error: ") + error;
	for (const FString& warning : Warnings)
		result += TEXT("\n  warning: ") + warning;
	return result;
}

bool FInkpotNativeBindingGenerator::IsLoaderFile(const FString& InFilename)
{
	return InFilename.EndsWith(LoaderSuffix(), ESearchCase::IgnoreCase);
}

FString FInkpotNativeBindingGenerator::LoaderFileFor(const FString& InModuleFile)
{
	return FPaths::GetPath(InModuleFile) / (FPaths::GetBaseFilename(InModuleFile) + LoaderSuffix());
}

TArray<FString> FInkpotNativeBindingGenerator::DiscoverModuleFiles(const FString& InDirectory)
{
	TArray<FString> files;
	IFileManager::Get().FindFilesRecursive(files, *InDirectory, TEXT("*.cpp"), true, false);
	TArray<FString> modules;
	for (const FString& file : files)
	{
		if (IsLoaderFile(file))
			continue;
		FString content;
		if (FFileHelper::LoadFileToString(content, *file) && FInkpotNativeBindingSourceScanner::LooksLikeModule(content))
			modules.Add(FPaths::ConvertRelativePathToFull(file));
	}
	modules.Sort();
	return modules;
}

EInkpotNativeBindingSource FInkpotNativeBindingGenerator::ClassifySource(const FInkpotNativeBindingSourceModule& InModule, const FProsettaNativeBindingsManifest* InManifest)
{
	if (InModule.Provenance.bPresent)
		return EInkpotNativeBindingSource::Prosetta;
	if (InManifest && InManifest->bValid && InManifest->FindModule(InModule.ModuleName))
		return EInkpotNativeBindingSource::Prosetta;
	return EInkpotNativeBindingSource::Local;
}

FString FInkpotNativeBindingGenerator::GenerateLoader(const FInkpotNativeBindingSourceModule& InModule, EInkpotNativeBindingSource InSource, const FProsettaNativeBindingLanguageEntry* InManifestEntry)
{
	const bool bProsetta = InSource == EInkpotNativeBindingSource::Prosetta;
	FString sha;
	if (bProsetta)
		sha = InManifestEntry && !InManifestEntry->SourceSha256.IsEmpty() ? InManifestEntry->SourceSha256 : InModule.Provenance.bPresent ? InModule.Provenance.SourceSha256 : InModule.AuthoredSha256;

	TArray<FString> lines;
	lines.Add(TEXT("// Generated by Inkpot. Do not edit; regenerate with Prosetta.NativeBindings.Generate."));
	lines.Add(FString::Printf(TEXT("// inkpot-native-binding module=%s source=%s%s"), *InModule.ModuleName, bProsetta ? TEXT("prosetta") : TEXT("local"), sha.IsEmpty() ? TEXT("") : *(TEXT(" authored-sha256=") + sha)));
	lines.Add(FString::Printf(TEXT("// Registers the functions of namespace Prosetta::Bindings::%s with the Inkpot native binding registry."), *InModule.ModuleName));
	lines.Add(TEXT("#include \"Inkpot/NativeBindings/InkpotNativeBinding.h\""));
	lines.Add(TEXT(""));
	lines.Add(FString::Printf(TEXT("namespace Prosetta::Bindings::%s"), *InModule.ModuleName));
	lines.Add(TEXT("{"));
	for (const FInkpotNativeBindingSourceFunction& function : InModule.Functions)
		lines.Add(FString::Printf(TEXT("\t%s;"), *function.Signature()));
	lines.Add(TEXT("}"));
	lines.Add(TEXT(""));
	lines.Add(FString::Printf(TEXT("INKPOT_NATIVE_BINDING_MODULE_BEGIN(%s, EInkpotNativeBindingSource::%s, \"%s\")"), *InModule.ModuleName, bProsetta ? TEXT("Prosetta") : TEXT("Local"), *sha));
	for (const FInkpotNativeBindingSourceFunction& function : InModule.Functions)
	{
		bool bLookaheadSafe = function.bLookaheadSafe;
		if (InManifestEntry)
			if (const FProsettaNativeBindingFunction* declared = InManifestEntry->FindFunction(function.Name))
				bLookaheadSafe = declared->bLookaheadSafe;
		lines.Add(FString::Printf(TEXT("\tINKPOT_NATIVE_BINDING(%s, %s)"), *function.Name, bLookaheadSafe ? TEXT("true") : TEXT("false")));
	}
	lines.Add(FString::Printf(TEXT("INKPOT_NATIVE_BINDING_MODULE_END(%s)"), *InModule.ModuleName));
	lines.Add(TEXT(""));
	return FString::Join(lines, TEXT("\n"));
}

void FInkpotNativeBindingGenerator::CompareWithManifest(const FInkpotNativeBindingSourceModule& InModule, const FProsettaNativeBindingsManifest& InManifest, TArray<FString>& OutErrors, TArray<FString>& OutWarnings)
{
	const FString name = InModule.ModuleName;
	const FProsettaNativeBindingModule* module = InManifest.FindModule(name);
	const FProsettaNativeBindingLanguageEntry* cpp = module ? module->FindCpp() : nullptr;
	if (!module || !cpp)
	{
		if (InModule.Provenance.bPresent)
			OutErrors.Add(FString::Printf(TEXT("%s: carries a Prosetta header but the manifest has no C++ entry for it; it was removed in Prosetta. Delete the local copy."), *name));
		else
			OutWarnings.Add(FString::Printf(TEXT("%s: not in the Prosetta manifest; treated as a local module."), *name));
		return;
	}
	if (!cpp->IsShipped())
	{
		OutErrors.Add(FString::Printf(TEXT("%s: the manifest excludes this module ( %s ); Prosetta serves no file for it, so the local copy is stale. Fix and save it in Prosetta, then sync again."), *name, *cpp->Reason));
		return;
	}
	if (!cpp->SourceSha256.IsEmpty() && !InModule.AuthoredSha256.Equals(cpp->SourceSha256, ESearchCase::IgnoreCase))
		OutErrors.Add(FString::Printf(TEXT("%s: local source sha256 %s differs from the manifest's %s; sync again before generating."), *name, *InModule.AuthoredSha256.Left(12), *cpp->SourceSha256.Left(12)));
	for (const FProsettaNativeBindingFunction& declared : cpp->Functions)
	{
		const FInkpotNativeBindingSourceFunction* function = InModule.FindFunction(declared.Name);
		if (!function)
		{
			OutErrors.Add(FString::Printf(TEXT("%s::%s: listed in the manifest but not found in the source."), *name, *declared.Name));
			continue;
		}
		if (function->Arity() != declared.Arity)
			OutErrors.Add(FString::Printf(TEXT("%s::%s: source arity %d, manifest arity %d."), *name, *declared.Name, function->Arity(), declared.Arity));
		if (function->bLookaheadSafe != declared.bLookaheadSafe)
			OutWarnings.Add(FString::Printf(TEXT("%s::%s: source lookaheadSafe=%s, manifest lookaheadSafe=%s; the manifest value is used."), *name, *declared.Name, function->bLookaheadSafe ? TEXT("true") : TEXT("false"), declared.bLookaheadSafe ? TEXT("true") : TEXT("false")));
	}
	for (const FInkpotNativeBindingSourceFunction& function : InModule.Functions)
		if (!cpp->FindFunction(function.Name))
			OutErrors.Add(FString::Printf(TEXT("%s::%s: in the source but not in the manifest."), *name, *function.Name));
	for (const FProsettaExternalDeclaration& external : InManifest.Externals)
	{
		const FInkpotNativeBindingSourceFunction* function = InModule.FindFunction(external.Name);
		if (function && function->Arity() != external.Arity)
			OutErrors.Add(FString::Printf(TEXT("%s::%s: takes %d parameter(s) but the Ink EXTERNAL declares %d."), *name, *external.Name, function->Arity(), external.Arity));
	}
}

FInkpotNativeBindingGenerationReport FInkpotNativeBindingGenerator::Run(const FString& InDirectory, const FProsettaNativeBindingsManifest* InManifest, bool bWrite)
{
	FInkpotNativeBindingGenerationReport report;
	report.Directory = FPaths::ConvertRelativePathToFull(InDirectory);
	report.bManifestUsed = InManifest && InManifest->bValid;
	if (!IFileManager::Get().DirectoryExists(*report.Directory))
	{
		report.Errors.Add(FString::Printf(TEXT("Directory '%s' does not exist."), *report.Directory));
		return report;
	}

	TMap<FString, FString> seenModules;
	TMap<FString, FString> seenFunctions;
	for (const FString& file : DiscoverModuleFiles(report.Directory))
	{
		FInkpotNativeBindingSourceModule module;
		FInkpotNativeBindingSourceScanner::ScanFile(file, module, true);
		const int32 index = report.Modules.Add(module);
		FInkpotNativeBindingSourceModule& scanned = report.Modules[index];
		if (!scanned.IsValid())
		{
			report.Errors.Add(FString::Printf(TEXT("%s: %d validation error(s); no loader generated."), *FPaths::GetCleanFilename(file), scanned.ErrorCount()));
			continue;
		}
		if (const FString* previous = seenModules.Find(scanned.ModuleName.ToLower()))
		{
			report.Errors.Add(FString::Printf(TEXT("%s: module '%s' is also defined in %s; module names must be unique."), *FPaths::GetCleanFilename(file), *scanned.ModuleName, *FPaths::GetCleanFilename(*previous)));
			continue;
		}
		seenModules.Add(scanned.ModuleName.ToLower(), file);

		bool bBlocked = false;
		for (const FInkpotNativeBindingSourceFunction& function : scanned.Functions)
		{
			if (const FString* owner = seenFunctions.Find(function.Name))
			{
				report.Errors.Add(FString::Printf(TEXT("%s::%s is also implemented by module %s; Ink binds one name to one function."), *scanned.ModuleName, *function.Name, **owner));
				bBlocked = true;
			}
			else
			{
				seenFunctions.Add(function.Name, scanned.ModuleName);
			}
		}

		const FProsettaNativeBindingLanguageEntry* manifestEntry = nullptr;
		if (report.bManifestUsed)
		{
			TArray<FString> errors, warnings;
			CompareWithManifest(scanned, *InManifest, errors, warnings);
			report.Errors.Append(errors);
			report.Warnings.Append(warnings);
			if (errors.Num() > 0)
				bBlocked = true;
			if (const FProsettaNativeBindingModule* manifestModule = InManifest->FindModule(scanned.ModuleName))
				manifestEntry = manifestModule->FindCpp();
		}
		if (bBlocked)
			continue;

		FInkpotNativeBindingGeneratedLoader loader;
		loader.ModuleName = scanned.ModuleName;
		loader.ModuleFile = file;
		loader.LoaderFile = LoaderFileFor(file);
		loader.Source = ClassifySource(scanned, InManifest);
		loader.Content = GenerateLoader(scanned, loader.Source, manifestEntry);
		FString existing;
		loader.bChanged = !FFileHelper::LoadFileToString(existing, *loader.LoaderFile) || existing != loader.Content;
		if (bWrite && loader.bChanged)
		{
			if (FFileHelper::SaveStringToFile(loader.Content, *loader.LoaderFile, FFileHelper::EEncodingOptions::ForceUTF8WithoutBOM))
				loader.bWritten = true;
			else
				report.Errors.Add(FString::Printf(TEXT("Cannot write loader '%s'."), *loader.LoaderFile));
		}
		report.Loaders.Add(MoveTemp(loader));
	}

	// Manifest modules with no local source yet.
	if (report.bManifestUsed)
	{
		for (const FProsettaNativeBindingModule* module : InManifest->GetShippedCppModules())
			if (!seenModules.Contains(module->ModuleName.ToLower()))
				report.Warnings.Add(FString::Printf(TEXT("%s: shipped by Prosetta ( %s ) but not present in %s; import it to bind its functions."), *module->ModuleName, *module->FindCpp()->RelativePath, *report.Directory));
	}

	report.bOk = report.Errors.Num() == 0;
	return report;
}
